#!/usr/bin/env node
/**
 * Builds an upload-ready CDIMS package for cPanel / shared hosting.
 *
 *   node scripts/build-release.mjs                 -> app at the domain root          (https://example.zm/)
 *   node scripts/build-release.mjs --base=/cdims/  -> app in a sub-folder             (https://example.zm/cdims/)
 *   node scripts/build-release.mjs --no-https      -> do not force HTTPS (testing on plain http only)
 *   node scripts/build-release.mjs --no-zip        -> skip creating release/cdims-release.zip
 *
 * Output (release/):
 *   public_html/   upload into the web root (or into the sub-folder): the built site, api/, install.php, .htaccess
 *   cdims-core/    upload ABOVE the web root (private): config, classes, cron, storage, env.example
 *   DEPLOYMENT.md  the step-by-step guide
 */
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (name) => args.find((a) => a.startsWith(`--${name}=`))?.split('=').slice(1).join('=');
const flag = (name) => args.includes(`--${name}`);

let base = opt('base') || '/';
if (!base.startsWith('/')) base = `/${base}`;
base = base.replace(/\/?$/, '/');
if (/^\/[A-Za-z]:\//.test(base)) {
  console.error('The base path was rewritten by Git Bash (' + base + '). Run again with MSYS_NO_PATHCONV=1 or write --base=cdims-test');
  process.exit(1);
}
const forceHttps = !flag('no-https');

const out = join(root, 'release');
const web = join(out, 'public_html');
const core = join(out, 'cdims-core');
const log = (m) => console.log(`\x1b[36m[release]\x1b[0m ${m}`);

rmSync(out, { recursive: true, force: true });
mkdirSync(web, { recursive: true });
mkdirSync(core, { recursive: true });

// ---- 1. build the React app for the chosen base path
log(`Building the front end for base "${base}" ...`);
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
if (!existsSync(join(root, 'frontend', 'node_modules'))) {
  const i = spawnSync(npm, ['install'], { cwd: join(root, 'frontend'), stdio: 'inherit', shell: true });
  if (i.status !== 0) process.exit(i.status ?? 1);
}
const b = spawnSync(npm, ['run', 'build'], {
  cwd: join(root, 'frontend'),
  stdio: 'inherit',
  shell: true,
  env: { ...process.env, VITE_BASE: base, VITE_OUTDIR: web },
});
if (b.status !== 0) process.exit(b.status ?? 1);

// ---- 2. PHP files
log('Copying the API, installer and backend ...');
cpSync(join(root, 'api'), join(web, 'api'), { recursive: true });
cpSync(join(root, 'deploy', 'install.php'), join(web, 'install.php'));
for (const dir of ['config', 'includes', 'cron']) cpSync(join(root, dir), join(core, dir), { recursive: true });
cpSync(join(root, 'setup.php'), join(core, 'setup.php'));
mkdirSync(join(core, 'storage'), { recursive: true });
cpSync(join(root, 'storage', '.htaccess'), join(core, 'storage', '.htaccess'));
cpSync(join(root, 'deploy', 'env.example'), join(core, 'env.example'));
if (existsSync(join(root, 'DEPLOYMENT.md'))) cpSync(join(root, 'DEPLOYMENT.md'), join(out, 'DEPLOYMENT.md'));

// ---- 3. .htaccess for the web root / sub-folder
const csp =
  "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com data:; " +
  "img-src 'self' data: blob: https://tile.openstreetmap.org https://*.tile.openstreetmap.org; connect-src 'self'; worker-src 'self'; manifest-src 'self'; " +
  "object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'";

const htaccess = `# CDIMS - generated by scripts/build-release.mjs (base "${base}")
Options -Indexes
AddDefaultCharset UTF-8
AddType application/manifest+json .webmanifest

<IfModule mod_headers.c>
    Header always set X-Frame-Options "DENY"
    Header always set X-Content-Type-Options "nosniff"
    Header always set Referrer-Policy "strict-origin-when-cross-origin"
    Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=()"
    Header always unset X-Powered-By
${forceHttps ? '    Header always set Strict-Transport-Security "max-age=31536000"\n' : ''}    Header always set Content-Security-Policy "${csp}"

    # Hashed build files never change: cache for a year. The page shell, service worker and manifest must always be re-checked.
    <FilesMatch "\\.(js|css|woff2?|png|svg|ico)$">
        Header set Cache-Control "public, max-age=31536000, immutable"
    </FilesMatch>
    <FilesMatch "^(index\\.html|sw\\.js|manifest\\.webmanifest|theme-init\\.js)$">
        Header set Cache-Control "no-cache"
    </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
    AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml application/manifest+json
</IfModule>

RewriteEngine On
RewriteBase ${base}
${forceHttps ? `
# Always use HTTPS (also behind a proxy that terminates TLS)
RewriteCond %{HTTPS} off
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
` : ''}
# Never serve private files, even if they are uploaded here by mistake
RewriteRule (^|/)\\.(env|git|cdims|ht)  - [F,L]
RewriteRule ^(cdims-core|config|includes|cron|storage)(/|$) - [F,L]
RewriteRule \\.(env|md|sql|log|lock|bak)$ - [F,L]

# The API has its own rules (api/.htaccess)
RewriteRule ^api/ - [L]

# Real files are served as they are; every other address is a page of the React app
RewriteCond %{REQUEST_FILENAME} -f
RewriteRule ^ - [L]
RewriteRule ^install\\.php$ - [L]
RewriteRule ^ index.html [L]
`;
writeFileSync(join(web, '.htaccess'), htaccess);

// ---- 4. check, report, zip
const count = (d) => readdirSync(d, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? count(join(d, e.name)) : 1), 0);
log(`public_html: ${count(web)} files, cdims-core: ${count(core)} files`);

if (!flag('no-zip')) {
  const zip = join(out, 'cdims-release.zip');
  const entries = ['public_html', 'cdims-core', ...(existsSync(join(out, 'DEPLOYMENT.md')) ? ['DEPLOYMENT.md'] : [])];
  const z =
    process.platform === 'win32'
      ? spawnSync(join(process.env.SystemRoot || 'C:\Windows', 'System32', 'tar.exe'), ['-a', '-c', '-f', 'cdims-release.zip', ...entries], { cwd: out, stdio: 'inherit' })
      : spawnSync('zip', ['-r', '-q', zip, ...entries], { cwd: out, stdio: 'inherit' });
  if (z.status === 0 && existsSync(zip)) log(`Created ${zip} (${(statSync(zip).size / 1048576).toFixed(1)} MB)`);
  else log('Could not create the zip automatically - zip the "release" folder contents yourself.');
}
log('Done. Follow DEPLOYMENT.md to upload and install.');
