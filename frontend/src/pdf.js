// Report PDFs are built in the browser. jsPDF is loaded only when a download is requested.
const BRAND = [11, 110, 153];
const INK = [20, 30, 45];
const MUTED = [100, 112, 128];
import { MONTHS, monthKeysOf, monthLabel, possibleDays } from './reportUtil';

const num = (v, u = '') => (v == null || v === '' || Number.isNaN(Number(v)) ? 'No data' : `${v}${u}`);

async function load() {
  const [{ jsPDF }, autoTableModule] = await Promise.all([import('jspdf'), import('jspdf-autotable')]);
  return { jsPDF, autoTable: autoTableModule.default };
}

/** Light shading for cells that hold no data, so they are not mistaken for zeros. */
const NO_DATA_FILL = [238, 241, 245];
const AMBER_FILL = [254, 243, 199];
const RED_FILL = [254, 226, 226];
const GREEN_FILL = [220, 252, 231];

function daysFill(days, possible) {
  if (!days) return RED_FILL;
  return days >= possible * 0.9 ? GREEN_FILL : AMBER_FILL;
}

function start(jsPDF, orientation, title, subtitle, notes = []) {
  const doc = new jsPDF({ orientation, unit: 'pt', format: 'a4' });
  const w = doc.internal.pageSize.getWidth();
  doc.setTextColor(...INK);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(19);
  doc.text(title, 40, 70);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  doc.setTextColor(...MUTED);
  doc.text(subtitle, 40, 88);
  let y = 104;
  doc.setFontSize(9);
  notes.forEach((n) => {
    const lines = doc.splitTextToSize(n, w - 80);
    doc.text(lines, 40, y);
    y += lines.length * 11;
  });
  return { doc, y: y + 8 };
}

/** Brand band and footer on every page, once the page count is known. */
function finish(doc, ctx, filename) {
  const pages = doc.internal.getNumberOfPages();
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFillColor(...BRAND);
    doc.rect(0, 0, w, 34, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.text(ctx.brand || 'CDIMS', 40, 22);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text(ctx.tagline || 'Zambia Meteorology Department', w - 40, 22, { align: 'right' });
    doc.setTextColor(...MUTED);
    doc.setFontSize(8);
    doc.text(ctx.footer || `Generated by CDIMS on ${new Date().toLocaleString()} for ${ctx.user}`, 40, h - 22);
    doc.text(`Page ${i} of ${pages}`, w - 40, h - 22, { align: 'right' });
  }
  doc.save(filename);
}

const baseTable = {
  theme: 'grid',
  styles: { fontSize: 8.5, cellPadding: 4, lineColor: [225, 230, 238], lineWidth: 0.5, textColor: INK },
  headStyles: { fillColor: BRAND, textColor: 255, fontStyle: 'bold' },
  margin: { top: 50, left: 40, right: 40, bottom: 40 },
};

function sampleNote(ctx) {
  return ctx.sampleShare > 0
    ? [`Note: ${Math.round(ctx.sampleShare * 100)}% of the readings in the system are generated demonstration data, not real measurements.`]
    : [];
}

/** Monthly summary per station, for a calendar year or a custom range. */
export async function downloadSummaryPdf(data, ctx) {
  const { jsPDF, autoTable } = await load();
  const custom = !!data.range;
  const title = custom ? 'Climate summary' : `Climate summary ${data.year}`;
  const period = custom ? `${data.range.from} to ${data.range.to}` : `Calendar year ${data.year}`;
  const { doc, y: y0 } = start(jsPDF, 'portrait', title, `${period} · ${ctx.scope}`, [
    'No data means no reading was reported for that month. 0 mm means rain was measured and none fell. A rain day is a day with 1 mm or more.',
    ...sampleNote(ctx),
  ]);
  const h = doc.internal.pageSize.getHeight();
  let y = y0;

  const monthKeys = monthKeysOf(data);
  const labelOf = monthLabel;
  const possible = (k) => possibleDays(data, k);

  data.stations.forEach((s) => {
    if (y > h - 250) { doc.addPage(); y = 60; }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(...INK);
    doc.text(`${s.name} (${s.code})`, 40, y);
    y += 8;

    autoTable(doc, {
      ...baseTable, startY: y,
      head: [['Avg max', 'Avg min', 'Rainfall', 'Rain days', 'Hottest', 'Coldest', 'Days reported']],
      body: [[num(s.year.tmax, '°C'), num(s.year.tmin, '°C'), num(s.year.rain, ' mm'), String(s.year.rain_days),
        num(s.year.hottest, '°C'), num(s.year.coldest, '°C'), String(s.year.days)]],
      headStyles: { ...baseTable.headStyles, fillColor: [60, 80, 100] },
      styles: { ...baseTable.styles, halign: 'center', fontStyle: 'bold' },
    });
    y = doc.lastAutoTable.finalY + 8;

    const rows = monthKeys.map((k) => {
      const x = s.months[k];
      const p = possible(k);
      if (x) return [labelOf(k), num(x.tmax, '°C'), num(x.tmin, '°C'), num(x.rain, ' mm'), String(x.rain_days), `${x.days} / ${p ?? x.days}`];
      if (p === null) return [labelOf(k), { content: 'Not reached yet', colSpan: 4, styles: { fontStyle: 'italic', textColor: MUTED, fillColor: [248, 249, 251] } }, 'n/a'];
      return [labelOf(k), { content: 'No data reported this month', colSpan: 4, styles: { fontStyle: 'italic', textColor: MUTED, fillColor: NO_DATA_FILL } }, `0 / ${p}`];
    });
    autoTable(doc, {
      ...baseTable, startY: y,
      head: [['Month', 'Avg max', 'Avg min', 'Rainfall', 'Rain days', 'Days reported']],
      body: rows,
      columnStyles: { 0: { fontStyle: 'bold' }, 1: { halign: 'right' }, 2: { halign: 'right' }, 3: { halign: 'right' }, 4: { halign: 'right' }, 5: { halign: 'right' } },
      didParseCell: (d) => {
        if (d.section === 'body' && d.column.index === 5) {
          const k = monthKeys[d.row.index];
          const x = s.months[k];
          const p = possible(k);
          if (p === null && !x) { d.cell.styles.textColor = MUTED; return; } // future month: neutral
          d.cell.styles.fillColor = daysFill(x ? x.days : 0, p ?? x.days);
        }
        if (d.section === 'body' && d.column.index === 0 && !s.months[monthKeys[d.row.index]]) d.cell.styles.textColor = MUTED;
      },
    });
    y = doc.lastAutoTable.finalY + 26;
  });

  doc.setFontSize(8);
  doc.setTextColor(...MUTED);
  if (y > h - 70) { doc.addPage(); y = 60; }
  doc.text(`Days reported: green = 90% or more of the days that could be reported, amber = incomplete, red = none. Data runs to ${data.as_of || 'n/a'}; later months are shown as not reached yet.`, 40, y);
  finish(doc, ctx, `cdims-climate-summary-${custom ? `${data.range.from}_${data.range.to}` : data.year}.pdf`);
}

/** Station by month heatmap, with cell colours matching the on-screen scale. */
export async function downloadHeatPdf(data, cfg, ctx) {
  const { jsPDF, autoTable } = await load();
  const { doc, y } = start(jsPDF, 'landscape', `${cfg.label} by station and month`, `Calendar year ${data.year} · ${ctx.scope}`, sampleNote(ctx));
  const vals = data.stations.flatMap((s) => Object.values(s.months).map((m) => Number(m[cfg.key]))).filter((v) => !Number.isNaN(v));
  const lo = Math.min(...vals);
  const hi = Math.max(...vals);
  const colour = (v) => cfg.from.map((c, i) => Math.round(c + (cfg.to[i] - c) * (hi === lo ? 0.5 : (v - lo) / (hi - lo))));

  autoTable(doc, {
    ...baseTable, startY: y,
    head: [['Station', ...MONTHS]],
    body: data.stations.map((s) => [s.name, ...MONTHS.map((_, i) => {
      const x = s.months[i + 1];
      const v = x ? Number(x[cfg.key]) : NaN;
      return Number.isNaN(v) ? 'No data' : String(Math.round(v));
    })]),
    columnStyles: { 0: { fontStyle: 'bold', cellWidth: 90 } },
    styles: { ...baseTable.styles, halign: 'center', fontSize: 8 },
    didParseCell: (d) => {
      if (d.section !== 'body' || d.column.index === 0) return;
      const x = data.stations[d.row.index].months[d.column.index];
      const v = x ? Number(x[cfg.key]) : NaN;
      if (Number.isNaN(v)) {
        d.cell.styles.fillColor = NO_DATA_FILL;
        d.cell.styles.textColor = MUTED;
        d.cell.styles.fontStyle = 'italic';
        d.cell.styles.fontSize = 6.5;
      } else {
        d.cell.styles.fillColor = colour(v);
        d.cell.styles.textColor = [15, 23, 42];
      }
    },
  });
  doc.setFontSize(8.5);
  doc.setTextColor(...MUTED);
  doc.text(`Scale: ${Math.round(lo)}${cfg.unit} (lightest) to ${Math.round(hi)}${cfg.unit} (darkest). Grey cells have no data.`, 40, doc.lastAutoTable.finalY + 18);
  finish(doc, ctx, `cdims-heatmap-${cfg.key}-${data.year}.pdf`);
}

/** Year-by-year comparison for one station or the national average. */
export async function downloadComparePdf(data, ctx) {
  const { jsPDF, autoTable } = await load();
  const { doc, y } = start(jsPDF, 'portrait', 'Year-by-year comparison', ctx.scope, [
    'Years with fewer than 300 days of data are partial and should not be compared directly with full years.',
    ...sampleNote(ctx),
  ]);
  autoTable(doc, {
    ...baseTable, startY: y,
    head: [['Year', 'Avg max', 'Avg min', 'Rainfall', 'Rain days', 'Hottest', 'Coldest', 'Days of data']],
    body: data.rows.map((r) => [String(r.year), num(r.tmax, '°C'), num(r.tmin, '°C'), num(r.rain, ' mm'), String(r.rain_days), num(r.hottest, '°C'), num(r.coldest, '°C'),
      String(Math.round(r.readings / Math.max(1, r.stations)))]),
    columnStyles: { 0: { fontStyle: 'bold' } },
    didParseCell: (d) => {
      if (d.section === 'body' && d.column.index === 7) {
        const days = Number(d.cell.raw);
        d.cell.styles.fillColor = days >= 300 ? GREEN_FILL : days > 0 ? AMBER_FILL : RED_FILL;
      }
    },
  });
  finish(doc, ctx, 'cdims-year-comparison.pdf');
}

/** Data completeness and quality indicators. */
export async function downloadQualityPdf(q, ctx) {
  const { jsPDF, autoTable } = await load();
  const t = q.totals;
  const { doc, y } = start(jsPDF, 'portrait', 'Data quality report', `Completeness over the 30 days to ${q.latest} · ${ctx.scope}`, sampleNote(ctx));

  autoTable(doc, {
    ...baseTable, startY: y,
    head: [['Readings', 'Flagged (suspect or estimated)', 'Retained deletions', 'Sample data']],
    body: [[Number(t.readings).toLocaleString(), Number(t.flagged).toLocaleString(), Number(t.deleted).toLocaleString(), Number(t.sample).toLocaleString()]],
    styles: { ...baseTable.styles, halign: 'center', fontStyle: 'bold' },
  });
  autoTable(doc, {
    ...baseTable, startY: doc.lastAutoTable.finalY + 16,
    head: [['Station', 'Status', 'Completeness', 'Days reported', 'Flagged', 'Last reading']],
    body: q.stations.map((s) => [`${s.name} (${s.code})`, s.status, `${s.completeness}%`, `${s.days_reported} / 30`, String(s.flagged), s.last_reading || 'No data']),
    didParseCell: (d) => {
      if (d.section !== 'body') return;
      if (d.column.index === 2) {
        const c = Number(String(d.cell.raw).replace('%', ''));
        d.cell.styles.fillColor = c >= 90 ? GREEN_FILL : c > 0 ? AMBER_FILL : RED_FILL;
      }
      if (d.column.index === 5 && d.cell.raw === 'No data') {
        d.cell.styles.fillColor = NO_DATA_FILL;
        d.cell.styles.textColor = MUTED;
        d.cell.styles.fontStyle = 'italic';
      }
    },
  });
  if (q.origins?.length) {
    doc.setFontSize(8.5);
    doc.setTextColor(...MUTED);
    doc.text(`Data origin: ${q.origins.map((o) => `${o.origin} ${Number(o.n).toLocaleString()}`).join(' · ')}`, 40, doc.lastAutoTable.finalY + 18);
  }
  finish(doc, ctx, 'cdims-data-quality.pdf');
}

// ======================================================================= public bulletins and alerts

const SEV = {
  advisory: { label: 'ADVISORY', fill: [37, 99, 235] },
  watch: { label: 'WATCH', fill: [217, 119, 6] },
  warning: { label: 'WARNING', fill: [220, 38, 38] },
};
const fmtDateTime = (d) => (d ? new Date(d.replace(' ', 'T')).toLocaleString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit' }) : '');
const fmtDay = (d) => new Date(`${d}T12:00:00`).toLocaleDateString('en-GB', { weekday: 'short', day: 'numeric', month: 'short' });

function pressCtx(meta) {
  return {
    brand: meta.org,
    tagline: meta.kind === 'alert' ? 'Weather alert' : 'Weather bulletin',
    footer: `Issued by ${meta.org}. Free to reproduce with attribution.`,
    user: meta.org,
  };
}

function demoNote(meta) {
  return meta.demo ? ['DEMONSTRATION DATA: this installation contains generated sample data. It must not be used for real decisions.'] : [];
}

/** A coloured banner with the alert level, used at the top of an alert PDF. */
function severityBanner(doc, severity, y) {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...SEV[severity].fill);
  doc.roundedRect(40, y, w - 80, 34, 4, 4, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text(`${SEV[severity].label} LEVEL`, 54, y + 22);
  doc.setTextColor(...INK);
  return y + 50;
}

function paragraph(doc, text, y, opts = {}) {
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  doc.setFont('helvetica', opts.bold ? 'bold' : 'normal');
  doc.setFontSize(opts.size || 10.5);
  doc.setTextColor(...(opts.color || INK));
  let yy = y;
  String(text).split('\n').forEach((line) => {
    const rows = doc.splitTextToSize(line || ' ', w - 80 - (opts.indent || 0));
    rows.forEach((r) => {
      if (yy > h - 60) { doc.addPage(); yy = 60; }
      doc.text(r, 40 + (opts.indent || 0), yy);
      yy += (opts.size || 10.5) * 1.45;
    });
  });
  return yy + (opts.after ?? 6);
}

function heading(doc, text, y) {
  const h = doc.internal.pageSize.getHeight();
  if (y > h - 90) { doc.addPage(); y = 60; }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12.5);
  doc.setTextColor(...BRAND);
  doc.text(text, 40, y);
  doc.setTextColor(...INK);
  return y + 14;
}

/** One alert, formatted for distribution. */
export async function downloadAlertPdf(a, meta) {
  const { jsPDF, autoTable } = await load();
  const m = { ...meta, kind: 'alert' };
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  let y = severityBanner(doc, a.severity, 52);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(19);
  doc.setTextColor(...INK);
  const titleRows = doc.splitTextToSize(a.title, doc.internal.pageSize.getWidth() - 80);
  doc.text(titleRows, 40, y + 6);
  y += titleRows.length * 24 + 6;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(...MUTED);
  doc.text(`${a.hazard_label} · ${a.basis === 'forecast' ? 'Forecast' : a.basis === 'observed' ? 'Based on observations' : 'Issued by forecaster'}`, 40, y);
  y += 14;
  if (a.status === 'cancelled') { y = paragraph(doc, `CANCELLED: ${a.cancel_reason}`, y + 4, { bold: true, color: [185, 28, 28] }); }
  demoNote(m).forEach((n) => { y = paragraph(doc, n, y + 2, { bold: true, color: [185, 28, 28], size: 9.5 }); });

  autoTable(doc, {
    ...baseTable, startY: y + 4, theme: 'plain',
    body: [
      ['Issued', fmtDateTime(a.published_at)],
      ['Valid from', fmtDateTime(a.starts_at)],
      ['Expires', fmtDateTime(a.expires_at)],
      ['Areas affected', a.areas.map((z) => `${z.name} (${z.province})`).join(', ')],
    ],
    styles: { fontSize: 10, cellPadding: { top: 3, bottom: 3, left: 0, right: 8 } },
    columnStyles: { 0: { fontStyle: 'bold', cellWidth: 90, textColor: MUTED } },
  });
  y = doc.lastAutoTable.finalY + 14;
  y = heading(doc, 'What is happening', y);
  y = paragraph(doc, a.message, y);
  if (a.advice) {
    y = heading(doc, 'What you should do', y + 4);
    y = paragraph(doc, a.advice, y);
  }
  y = paragraph(doc, `Alert reference: CDIMS-${a.id}. Alerts are checked by a forecaster before they are published. Observations are provisional and forecasts come from the Open-Meteo model. Machine-readable version (CAP 1.2): ${meta.capUrl}`, y + 8, { size: 8.5, color: MUTED });
  finish(doc, pressCtx(m), `${meta.org.replace(/\W+/g, '-').toLowerCase()}-alert-${a.id}.pdf`);
}

/** A daily bulletin or weekly summary, formatted for distribution. */
export async function downloadBulletinPdf(b, meta) {
  const { jsPDF, autoTable } = await load();
  const m = { ...meta, kind: 'bulletin' };
  const c = b.content || {};
  const { doc, y: y0 } = start(jsPDF, 'portrait', b.title, `${b.kind === 'daily' ? 'Daily weather bulletin' : 'Weekly climate summary'} · Issued ${fmtDateTime(b.published_at)}`, demoNote(m));
  let y = y0;

  y = heading(doc, 'Summary', y);
  y = paragraph(doc, b.summary, y);
  if (b.notes) y = paragraph(doc, b.notes, y, { size: 9.5, color: MUTED });

  if (c.alerts?.length) {
    y = heading(doc, 'Weather alerts in force', y + 4);
    autoTable(doc, {
      ...baseTable, startY: y,
      head: [['Level', 'Alert', 'Areas']],
      body: c.alerts.map((a) => [SEV[a.severity]?.label || a.severity, a.title, (a.areas || []).join(', ')]),
      didParseCell: (d) => {
        if (d.section === 'body' && d.column.index === 0) {
          const f = (SEV[c.alerts[d.row.index].severity] || SEV.watch).fill;
          d.cell.styles.fillColor = f; d.cell.styles.textColor = 255; d.cell.styles.fontStyle = 'bold';
        }
      },
      columnStyles: { 0: { cellWidth: 62 } },
    });
    y = doc.lastAutoTable.finalY + 16;
  }

  if (b.kind === 'daily') {
    y = heading(doc, `Observations for ${new Date(`${c.observed_on}T12:00:00`).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}`, y);
    autoTable(doc, {
      ...baseTable, startY: y,
      head: [['Station', 'Province', 'Max °C', 'Min °C', 'Rain mm', 'Humidity %', 'Wind m/s']],
      body: (c.observed || []).map((r) => [r.name, r.province, num(r.tmax), num(r.tmin), num(r.rain), num(r.humidity), num(r.wind)]),
      styles: { ...baseTable.styles, halign: 'center' }, columnStyles: { 0: { halign: 'left', fontStyle: 'bold' }, 1: { halign: 'left' } },
      didParseCell: (d) => { if (d.section === 'body' && d.cell.raw === 'No data') { d.cell.styles.textColor = MUTED; d.cell.styles.fontStyle = 'italic'; d.cell.styles.fontSize = 7; } },
    });
    y = doc.lastAutoTable.finalY + 16;
    if (c.outlook?.length) {
      y = heading(doc, 'Outlook, next three days', y);
      const dates = c.outlook[0].days.map((d) => d.date);
      autoTable(doc, {
        ...baseTable, startY: y,
        head: [['Station', ...dates.map(fmtDay)]],
        body: c.outlook.map((s) => [s.name, ...dates.map((dt) => { const d = s.days.find((x) => x.date === dt); return d ? `${Math.round(d.max)}/${Math.round(d.min)} °C\n${d.rain_mm ?? 0} mm (${d.rain_chance ?? 0}%)` : '-'; })]),
        styles: { ...baseTable.styles, halign: 'center', fontSize: 8 }, columnStyles: { 0: { halign: 'left', fontStyle: 'bold' } },
      });
      y = doc.lastAutoTable.finalY + 8;
      y = paragraph(doc, 'Outlook shows maximum/minimum temperature, expected rainfall and chance of rain. Source: Open-Meteo model forecast.', y, { size: 8.5, color: MUTED });
    }
  } else {
    y = heading(doc, 'Week at each station', y);
    autoTable(doc, {
      ...baseTable, startY: y,
      head: [['Station', 'Avg max', 'vs normal', 'Avg min', 'Rain mm', '% normal', 'Rain days']],
      body: (c.stations || []).map((r) => [r.name, num(r.tmax, '°'), r.tmax_anomaly == null ? 'n/a' : `${r.tmax_anomaly > 0 ? '+' : ''}${r.tmax_anomaly}°`, num(r.tmin, '°'), num(r.rain), r.rain_pct_normal == null ? 'n/a' : `${r.rain_pct_normal}%`, String(r.rain_days)]),
      styles: { ...baseTable.styles, halign: 'center' }, columnStyles: { 0: { halign: 'left', fontStyle: 'bold' } },
    });
    y = doc.lastAutoTable.finalY + 8;
    y = paragraph(doc, '"vs normal" and "% normal" compare with the same dates in earlier years in the record, and show n/a when there is not enough history.', y, { size: 8.5, color: MUTED });
    if (c.outlook?.length) {
      y = heading(doc, 'Outlook, next seven days', y + 4);
      autoTable(doc, {
        ...baseTable, startY: y,
        head: [['Station', 'Province', 'Expected rain', 'Avg max']],
        body: c.outlook.map((s) => [s.name, s.province, `${s.rain_mm} mm`, num(s.avg_max, ' °C')]),
        styles: { ...baseTable.styles, halign: 'center' }, columnStyles: { 0: { halign: 'left', fontStyle: 'bold' }, 1: { halign: 'left' } },
      });
    }
  }
  finish(doc, pressCtx(m), `${meta.org.replace(/\W+/g, '-').toLowerCase()}-${b.kind}-bulletin-${b.period_end}.pdf`);
}

/** Plain text of a bulletin or alert, for pasting into a news story, SMS or social post. */
export function pressText(item, kind, meta) {
  const lines = [];
  if (kind === 'alert') {
    lines.push(`${SEV[item.severity].label}: ${item.title}`, '', `Valid ${fmtDateTime(item.starts_at)} to ${fmtDateTime(item.expires_at)}`, `Areas: ${item.areas.map((z) => z.name).join(', ')}`, '', item.message);
    if (item.advice) lines.push('', `What to do: ${item.advice}`);
  } else {
    lines.push(item.title, `Issued ${fmtDateTime(item.published_at)}`, '', item.summary);
    (item.content?.alerts || []).forEach((a) => lines.push('', `${SEV[a.severity]?.label || a.severity}: ${a.title}`));
  }
  lines.push('', `Source: ${meta.org}.`);
  if (meta.demo) lines.push('NOTE: demonstration data, not for real decisions.');
  return lines.join('\n');
}
